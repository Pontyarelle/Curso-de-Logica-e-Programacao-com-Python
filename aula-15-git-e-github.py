# 1. Verificar se o Git está instalado:
# git --version

# 2. Configurar nome e e-mail (use seus próprios dados):
# git config --global user.name "Seu Nome"
# git config --global user.email "seu-email@example.com"

# 3. Dentro da pasta do projeto, iniciar o repositório:
# git init

# 4. Verificar os arquivos:
# git status

# 5. Preparar arquivos para o próximo commit:
# git add .

# 6. Registrar uma versão:
# git commit -m "Adiciona exemplos das aulas"

# 7. Conectar ao repositório remoto criado no GitHub:
# git remote add origin URL_DO_REPOSITORIO

# 8. Enviar o projeto:
# git branch -M main
# git push -u origin main

# 9. Nas próximas atualizações:
# git add .
# git commit -m "Descreve a alteração"
# git push

